"""Retrieval-query transformation with validation, retries, and safe fallback."""

import json
import logging
import re
from dataclasses import dataclass
from typing import Protocol

logger = logging.getLogger(__name__)

QUERY_TRANSFORMATION_SYSTEM_PROMPT = """
You are a retrieval query planner for a document RAG system.

Transform the user's question into focused queries that help retrieve the
evidence required to answer it.

Rules:
- Do not answer the question or add external knowledge.
- Preserve the original language and important entities, dates, identifiers,
  quantities, comparisons, negations, and constraints.
- Remove conversational or narrative details that do not help retrieval.
- Write concise natural-language queries, not bags of keywords.
- Each query must target one independent information need or relationship.
- A query is atomic when answering it would not leave another independently
  requested fact or relationship unanswered.
- If there is one information need, generate one query.
- If there are multiple independent information needs, split them into
  separate atomic queries.
- Do not merely paraphrase the full question when a more focused query is possible.
- Preserve the relationships and structure expressed in the original question.
- Return only valid JSON in this exact form:
  {"queries": ["query 1", "query 2"]}
""".strip()


class QueryTransformationProvider(Protocol):
    """
    Define the text-generation capability required for query transformation.

    The transformation service depends only on this protocol rather than on a
    concrete LLM implementation, allowing inference providers to be replaced
    without changing retrieval-planning logic.
    """

    async def generate(
        self,
        *,
        system_prompt: str,
        prompt: str,
    ) -> str:
        """
        Generate a query-transformation response.

        Args:
            system_prompt: Instructions controlling transformation behavior.
            prompt: User-specific transformation request.

        Returns:
            Raw text generated by the inference provider.
        """
        ...


@dataclass(frozen=True)
class QueryTransformationResult:
    """
    Describe the outcome of retrieval-query transformation.

    Attributes:
        original_query: Normalized question originally submitted by the user.
        retrieval_queries: Queries that should be used by the retrieval layer.
            The original query is preserved as the first candidate whenever
            transformation succeeds.
        used_fallback: Whether transformation failed and retrieval therefore
            fell back to the original query only.
        attempt_count: Number of transformation attempts performed.
    """

    original_query: str
    retrieval_queries: list[str]
    used_fallback: bool
    attempt_count: int


class QueryTransformationService:
    """
    Transform user questions into focused retrieval queries.

    The service asks an LLM to decompose or focus a question into atomic search
    queries while preserving the original question as a retrieval candidate.
    Generated output is strictly parsed and normalized before reaching the
    retrieval layer.

    Transformation is intentionally best-effort. Provider failures, malformed
    JSON, or unusable generated queries are retried up to the configured
    attempt limit. If transformation still fails, the service safely falls
    back to the original query so RAG execution can continue.
    """

    def __init__(
        self,
        provider: QueryTransformationProvider,
        *,
        max_generated_queries: int = 2,
        max_attempts: int = 2,
    ) -> None:
        """
        Initialize the query-transformation service.

        Args:
            provider: Text-generation provider used to create retrieval queries.
            max_generated_queries: Maximum number of transformed queries
                accepted from one provider response.
            max_attempts: Maximum number of transformation attempts before
                falling back to the original query.

        Raises:
            ValueError: If either configured limit is not greater than zero.
        """

        if max_generated_queries <= 0:
            raise ValueError("Max generated queries must be greater than zero")

        if max_attempts <= 0:
            raise ValueError("Max attempts must be greater than zero")

        self._provider = provider
        self._max_generated_queries = max_generated_queries
        self._max_attempts = max_attempts

    async def transform(
        self,
        query: str,
    ) -> QueryTransformationResult:
        """
        Generate validated retrieval queries for a user question.

        The original query is always preserved as the first retrieval
        candidate. Generated queries are appended after parsing and
        deduplication. If every transformation attempt fails, the method
        returns the original query as a safe fallback rather than propagating
        the provider or parsing failure.

        Args:
            query: User question to transform for retrieval.

        Returns:
            Transformation result containing the original query, final
            retrieval queries, fallback state, and number of attempts used.

        Raises:
            ValueError: If the supplied query is empty or whitespace-only.
        """

        original_query = query.strip()

        if not original_query:
            raise ValueError("Query cannot be empty")

        prompt = self._build_prompt(original_query)

        last_error: Exception | None = None

        for attempt in range(1, self._max_attempts + 1):
            try:
                response = await self._provider.generate(
                    system_prompt=QUERY_TRANSFORMATION_SYSTEM_PROMPT,
                    prompt=prompt,
                )

                generated_queries = self._parse_queries(response)

                retrieval_queries = self._deduplicate_queries(
                    [original_query, *generated_queries]
                )

                return QueryTransformationResult(
                    original_query=original_query,
                    retrieval_queries=retrieval_queries,
                    used_fallback=False,
                    attempt_count=attempt,
                )

            except Exception as exc:
                last_error = exc

                logger.warning(
                    "Query transformation attempt %s/%s failed: %s",
                    attempt,
                    self._max_attempts,
                    exc,
                )

        logger.warning(
            "Query transformation failed after %s attempts; "
            "falling back to original query. Last error: %s",
            self._max_attempts,
            last_error,
        )

        return QueryTransformationResult(
            original_query=original_query,
            retrieval_queries=[original_query],
            used_fallback=True,
            attempt_count=self._max_attempts,
        )

    def _build_prompt(self, query: str) -> str:
        """
        Build the provider prompt for a query-transformation request.

        Args:
            query: Normalized original user question.

        Returns:
            Prompt instructing the provider to generate a bounded number of
            retrieval queries in the original language.
        """

        return (
            f"Original question:\n"
            f"{query}\n\n"
            f"Generate at most {self._max_generated_queries} retrieval queries.\n"
            f"Write every retrieval query in the same language as the original question."
        )

    def _parse_queries(self, response: str) -> list[str]:
        """
        Parse and validate retrieval queries returned by the provider.

        Markdown code fences are tolerated so otherwise valid JSON responses
        remain usable. Only non-empty string entries are accepted, and the
        result is bounded by ``max_generated_queries``.

        Args:
            response: Raw text returned by the transformation provider.

        Returns:
            Normalized generated retrieval queries.

        Raises:
            json.JSONDecodeError: If the response does not contain valid JSON.
            ValueError: If the decoded response has an invalid structure or
                contains no usable queries.
        """

        cleaned = response.strip()

        if cleaned.startswith("```"):
            lines = cleaned.splitlines()

            if lines and lines[0].startswith("```"):
                lines = lines[1:]

            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]

            cleaned = "\n".join(lines).strip()

        data = json.loads(cleaned)

        if not isinstance(data, dict):
            raise ValueError("Query transformer response must be a JSON object")

        queries = data.get("queries")

        if not isinstance(queries, list):
            raise ValueError("Query transformer returned an invalid queries field")

        normalized_queries: list[str] = []

        for query in queries[: self._max_generated_queries]:
            if not isinstance(query, str):
                continue

            normalized = query.strip()

            if normalized:
                normalized_queries.append(normalized)

        if not normalized_queries:
            raise ValueError("Query transformer returned no usable queries")

        return normalized_queries

    def _deduplicate_queries(self, queries: list[str]) -> list[str]:
        """
        Remove duplicate retrieval queries while preserving their priority.

        Comparison is case-insensitive and ignores punctuation and repeated
        whitespace. The original query therefore remains first while generated
        paraphrases that normalize to the same text are discarded.

        Args:
            queries: Ordered retrieval-query candidates.

        Returns:
            Unique queries in their original priority order.
        """

        unique_queries: list[str] = []
        seen: set[str] = set()

        for query in queries:
            normalized = query.strip()

            key = normalized.casefold()
            key = re.sub(r"[^\w\s]", "", key)
            key = " ".join(key.split())

            if not normalized or key in seen:
                continue

            unique_queries.append(normalized)
            seen.add(key)

        return unique_queries
